package com.finora.finance.subscriptions;

import com.finora.commons.authz.Role;
import com.finora.commons.error.ApiException;
import com.finora.commons.error.ErrorCode;
import com.finora.finance.core.FinanceAudit;
import com.finora.finance.core.Validate;
import com.finora.finance.insights.InsightsContext;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.regex.Pattern;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Billing contact and billing history of one workspace. No payment provider is approved, so there is no way to take a payment, no price, and no record is
 * created by a user: records appear only from VERIFIED provider events (see {@link BillingEventProcessor}). A record is an application-generated billing record,
 * never a legally valid tax invoice and never a payment receipt; "payment confirmed" is true only for a record the database holds as PAID with the provider's
 * own reference. Raw card data is never accepted or stored anywhere.
 */
@Service
public class BillingService {

    private static final Pattern EMAIL = Pattern.compile("^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$");

    public record Contact(String contactName, String contactEmail, OffsetDateTime updatedAt) {
    }

    public record ContactRequest(String contactName, String contactEmail) {
    }

    public record Record(UUID id, String kind, boolean legalTaxInvoice, String status, boolean paymentConfirmed, String currency, String amount, String description, LocalDate periodStart,
            LocalDate periodEnd, String provider, String providerReference, OffsetDateTime paidAt, OffsetDateTime createdAt, List<Map<String, Object>> paymentAttempts) {
    }

    private record Row(UUID id, String status, String currency, java.math.BigDecimal amount, String description, LocalDate periodStart, LocalDate periodEnd, String provider,
            String providerReference, OffsetDateTime paidAt, OffsetDateTime createdAt) {
    }

    private final JdbcClient jdbc;
    private final FinanceAudit audit;

    public BillingService(JdbcClient jdbc, FinanceAudit audit) {
        this.jdbc = jdbc;
        this.audit = audit;
    }

    public Map<String, Object> overview(InsightsContext ctx) {
        ctx.requireSettingsRead();
        Contact contact = jdbc.sql("select contact_name, contact_email, updated_at from billing_accounts where tenant_id = :t").param("t", ctx.tenantId()).query(Contact.class).optional().orElse(null);
        return Map.of("provider", Map.of("status", "NOT_CONFIGURED", "approved", false),
                "message", "No payment provider has been approved or configured. No payment can be taken, no price applies, and no billing record is created automatically.",
                "payments_enabled", false, "contact", contact == null ? Map.of() : contact,
                "notes", List.of("A billing record is generated by the application. It is not a tax invoice and not a payment receipt.",
                        "A record is shown as paid only after a verified payment event from the payment provider; a message from your browser never marks anything paid."));
    }

    @Transactional
    public Contact putContact(InsightsContext ctx, ContactRequest req) {
        if (ctx.role() != Role.OWNER) {
            throw new ApiException(ErrorCode.FORBIDDEN, null);
        }
        String name = Validate.text("contact_name", req.contactName(), 1, 120, false);
        String email = req.contactEmail() == null || req.contactEmail().isBlank() ? null : req.contactEmail().trim();
        if (email != null && (email.length() > 254 || !EMAIL.matcher(email).matches())) {
            throw Validate.invalid("contact_email must be an email address");
        }
        jdbc.sql("""
                insert into billing_accounts (tenant_id, contact_name, contact_email, updated_by, updated_at) values (:t, :n, :e, :u, :now)
                on conflict (tenant_id) do update set contact_name = :n, contact_email = :e, updated_by = :u, updated_at = :now
                """).param("t", ctx.tenantId()).param("n", name).param("e", email).param("u", ctx.userId()).param("now", OffsetDateTime.ofInstant(ctx.clock().instant(), ZoneOffset.UTC)).update();
        audit.record(ctx.tenantId(), ctx.userId(), ctx.clock(), "BILLING_CONTACT_UPDATED", "BILLING_ACCOUNT", ctx.tenantId(), "email_set=" + (email != null));
        return jdbc.sql("select contact_name, contact_email, updated_at from billing_accounts where tenant_id = :t").param("t", ctx.tenantId()).query(Contact.class).single();
    }

    public Map<String, Object> records(InsightsContext ctx, int limit, int offset) {
        ctx.requireSettingsRead();
        int lim = Math.max(1, Math.min(100, limit));
        int off = Math.max(0, offset);
        long total = jdbc.sql("select count(*) from billing_records where tenant_id = :t").param("t", ctx.tenantId()).query(Long.class).single();
        List<Record> items = jdbc.sql("""
                select id, status, currency, amount, description, period_start, period_end, provider, provider_reference, paid_at, created_at from billing_records where tenant_id = :t
                order by created_at desc, id limit :l offset :o
                """).param("t", ctx.tenantId()).param("l", lim).param("o", off).query(Row.class).list().stream().map(r -> {
            List<Map<String, Object>> attempts = jdbc.sql("select status, provider, failure_code, event_at from payment_attempts where tenant_id = :t and billing_record_id = :r order by event_at desc")
                    .param("t", ctx.tenantId()).param("r", r.id()).query((rs, i) -> Map.<String, Object>of("status", rs.getString(1), "provider", rs.getString(2),
                            "failure_code", String.valueOf(rs.getString(3)), "event_at", String.valueOf(rs.getObject(4, OffsetDateTime.class)))).list();
            boolean confirmed = "PAID".equals(r.status()) && r.provider() != null && r.providerReference() != null;
            return new Record(r.id(), "APPLICATION_RECORD", false, r.status(), confirmed, r.currency().trim(), com.finora.finance.money.Currencies.format(r.amount(), r.currency().trim()), r.description(),
                    r.periodStart(), r.periodEnd(), r.provider(), r.providerReference(), r.paidAt(), r.createdAt(), attempts);
        }).toList();
        return Map.of("items", items, "total", total, "limit", lim, "offset", off);
    }
}
