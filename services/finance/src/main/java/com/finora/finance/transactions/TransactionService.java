/**
 * Income, expense, refund and transfer transactions. Amounts are exact decimals in the account's currency. A transfer is a
 * single record that moves money between the user's own accounts and is never income or expense. Only POSTED transactions
 * count towards balances and summaries; DRAFT (for example generated by a recurring rule) and VOIDED do not.
 */
@Service
public class TransactionService {

    public record Row(UUID id, String kind, String status, UUID accountId, UUID toAccountId, BigDecimal amount, String currency,
            BigDecimal toAmount, String toCurrency, String direction, UUID categoryId, UUID refundOf, LocalDate occurredOn,
            String payee, String note, UUID recurringRuleId, UUID commitmentId, int version, OffsetDateTime createdAt,
            OffsetDateTime updatedAt, String voidReason) {
    }

    public record View(UUID id, String kind, String status, UUID accountId, UUID toAccountId, String amount, String currency,
            String toAmount, String toCurrency, String direction, UUID categoryId, UUID refundOf, LocalDate occurredOn,
            String payee, String note, List<String> tags, UUID recurringRuleId, UUID commitmentId, int version,
            OffsetDateTime createdAt, OffsetDateTime updatedAt, String voidReason) {
    }

    public record Page(List<View> items, String nextCursor) {
    }

    public record CreateRequest(String kind, String accountId, String amount, String currency, String occurredOn,
            String categoryId, String payee, String note, List<String> tags, String refundOf) {
    }

    public record TransferRequest(String fromAccountId, String toAccountId, String amount, String toAmount, String occurredOn,
            String note) {
    }

    public record EditRequest(String amount, String toAmount, String occurredOn, String categoryId, Boolean uncategorized,
            String payee, String note, List<String> tags, Integer version) {
    }

    public record VoidRequest(String reason) {
    }

    public record Filter(LocalDate from, LocalDate to, UUID accountId, UUID categoryId, String kind, String status,
            boolean includeVoided, List<String> tags, boolean anyTag, String q, String cursor, Integer limit) {
    }

    static final String COLS = "id, kind, status, account_id, to_account_id, amount, currency, to_amount, to_currency, direction, "
            + "category_id, refund_of, occurred_on, payee, note, recurring_rule_id, commitment_id, version, created_at, updated_at, void_reason";

    private final JdbcClient jdbc;
    private final AccountService accounts;
    private final ReferenceService reference;
    private final FinanceAudit audit;

    public TransactionService(JdbcClient jdbc, AccountService accounts, ReferenceService reference, FinanceAudit audit) {
        this.jdbc = jdbc;
        this.accounts = accounts;
        this.reference = reference;
        this.audit = audit;
    }

    private static OffsetDateTime now(FinanceContext ctx) {
        return OffsetDateTime.ofInstant(ctx.clock().instant(), ZoneOffset.UTC);
    }

    // ---- reading ----

    public Row row(UUID tenant, UUID id, boolean lock) {
        return jdbc.sql("select " + COLS + " from transactions where tenant_id = :t and id = :id" + (lock ? " for update" : ""))
                .param("t", tenant).param("id", id).query(Row.class).optional()
                .orElseThrow(() -> new ApiException(ErrorCode.NOT_FOUND, null));
    }

    public View get(FinanceContext ctx, UUID id) {
        ctx.require(Action.READ);
        return views(ctx.tenantId(), List.of(row(ctx.tenantId(), id, false))).get(0);
    }

    List<View> views(UUID tenant, List<Row> rows) {
        if (rows.isEmpty()) {
            return List.of();
        }
        Map<UUID, List<String>> tags = new HashMap<>();
        jdbc.sql("""
                select tt.transaction_id as tx, t.name as name from transaction_tags tt
                join tags t on t.tenant_id = tt.tenant_id and t.id = tt.tag_id
                where tt.tenant_id = :t and tt.transaction_id in (:ids) order by t.name
                """).param("t", tenant).param("ids", rows.stream().map(Row::id).toList())
                .query((rs, n) -> Map.entry(rs.getObject(1, UUID.class), rs.getString(2))).list()
                .forEach(e -> tags.computeIfAbsent(e.getKey(), k -> new ArrayList<>()).add(e.getValue()));
        return rows.stream().map(r -> new View(r.id(), r.kind(), r.status(), r.accountId(), r.toAccountId(),
                Currencies.format(r.amount(), r.currency()), r.currency(),
                r.toAmount() == null ? null : Currencies.format(r.toAmount(), r.toCurrency()), r.toCurrency(), r.direction(),
                r.categoryId(), r.refundOf(), r.occurredOn(), r.payee(), r.note(), tags.getOrDefault(r.id(), List.of()),
                r.recurringRuleId(), r.commitmentId(), r.version(), r.createdAt(), r.updatedAt(), r.voidReason())).toList();
    }

    /** Newest first, keyset-paginated (stable under inserts), always scoped to the caller's profile. */
    public Page list(FinanceContext ctx, Filter f) {
        ctx.require(Action.READ);
        int limit = f.limit() == null ? 50 : f.limit();
        if (limit < 1 || limit > 200) {
            throw Validate.invalid("limit must be between 1 and 200");
        }
        if (f.from() != null && f.to() != null && f.from().isAfter(f.to())) {
            throw Validate.invalid("from must not be after to");
        }
        StringBuilder where = new StringBuilder("tenant_id = :t");
        Map<String, Object> p = new LinkedHashMap<>();
        p.put("t", ctx.tenantId());
        if (f.status() != null) {
            where.append(" and status = :status");
            p.put("status", f.status());
        } else if (!f.includeVoided()) {
            where.append(" and status <> 'VOIDED'");
        }
        if (f.from() != null) {
            where.append(" and occurred_on >= :from");
            p.put("from", f.from());
        }
        if (f.to() != null) {
            where.append(" and occurred_on <= :to");
            p.put("to", f.to());
        }
        if (f.accountId() != null) {
            where.append(" and (account_id = :acc or to_account_id = :acc)");
            p.put("acc", f.accountId());
        }
        if (f.categoryId() != null) {
            where.append(" and category_id in (:cats)");
            p.put("cats", reference.withChildren(ctx.tenantId(), f.categoryId()));
        }
        if (f.kind() != null) {
            where.append(" and kind = :kind");
            p.put("kind", f.kind());
        }
        if (f.tags() != null && !f.tags().isEmpty()) {
            where.append(" and (select count(distinct t.name) from transaction_tags tt join tags t on t.tenant_id = tt.tenant_id and t.id = tt.tag_id"
                    + " where tt.tenant_id = transactions.tenant_id and tt.transaction_id = transactions.id and t.name in (:tagNames)) ");
            where.append(f.anyTag() ? ">= 1" : "= :tagCount");
            p.put("tagNames", f.tags());
            p.put("tagCount", f.tags().size());
        }
        if (f.q() != null && !f.q().isBlank()) {
            String like = "%" + f.q().trim().replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%";
            where.append(" and (note ilike :q escape '\\' or payee ilike :q escape '\\')");
            p.put("q", like);
        }
        if (f.cursor() != null && !f.cursor().isBlank()) {
            try {
                String[] parts = new String(Base64.getUrlDecoder().decode(f.cursor()), StandardCharsets.UTF_8).split("\\|", 2);
                p.put("cd", LocalDate.parse(parts[0]));
                p.put("cid", UUID.fromString(parts[1]));
            } catch (RuntimeException e) {
                throw Validate.invalid("cursor is not valid");
            }
            where.append(" and (occurred_on, id) < (:cd, :cid)");
        }
        p.put("lim", limit + 1);
        List<Row> rows = new ArrayList<>(jdbc.sql("select " + COLS + " from transactions where " + where
                + " order by occurred_on desc, id desc limit :lim").params(p).query(Row.class).list());
        String next = null;
        if (rows.size() > limit) {
            rows = new ArrayList<>(rows.subList(0, limit));
            Row last = rows.get(rows.size() - 1);
            next = Base64.getUrlEncoder().withoutPadding().encodeToString((last.occurredOn() + "|" + last.id()).getBytes(StandardCharsets.UTF_8));
        }
        return new Page(views(ctx.tenantId(), rows), next);
    }

    // ---- creating ----

    private static void checkDate(FinanceContext ctx, LocalDate date, LocalDate... notBefore) {
        for (LocalDate opening : notBefore) {
            if (date.isBefore(opening)) {
                throw Validate.invalid("occurred_on is before the account's opening date (" + opening + ")");
            }
        }
        if (date.isAfter(ctx.today().plusDays(366))) {
            throw Validate.invalid("occurred_on is too far in the future");
        }
    }

    private void insertTags(FinanceContext ctx, UUID txId, List<String> names) {
        for (UUID tagId : reference.upsertTags(ctx, names)) {
            jdbc.sql("insert into transaction_tags (tenant_id, transaction_id, tag_id) values (:t, :x, :g) on conflict do nothing")
                    .param("t", ctx.tenantId()).param("x", txId).param("g", tagId).update();
        }
    }

    enum Creatable { INCOME, EXPENSE, REFUND }

    @Transactional
    public View create(FinanceContext ctx, CreateRequest req) {
        ctx.require(Action.CREATE);
        Creatable kind = Validate.choice("kind", req.kind(), Creatable.class);
        AccountService.Row account = accounts.requireUsable(ctx.tenantId(), Validate.uuid("account_id", req.accountId(), true), "account_id");
        if (req.currency() != null && !account.currency().equalsIgnoreCase(req.currency().trim())) {
            throw Validate.invalid("currency must match the account's currency (" + account.currency() + ")");
        }
        BigDecimal amount = Amounts.parse("amount", req.amount(), account.currency(), Amounts.Sign.POSITIVE);
        LocalDate date = Validate.date("occurred_on", req.occurredOn(), true);
        checkDate(ctx, date, account.openingDate());
        String payee = Validate.text("payee", req.payee(), 1, 120, false);
        String note = Validate.text("note", req.note(), 1, 1000, false);
        List<String> tags = Validate.tags(req.tags());
        UUID categoryId = null;
        UUID refundOf = null;
        if (kind == Creatable.REFUND) {
            refundOf = Validate.uuid("refund_of", req.refundOf(), true);
            Row original = jdbc.sql("select " + COLS + " from transactions where tenant_id = :t and id = :id for update")
                    .param("t", ctx.tenantId()).param("id", refundOf).query(Row.class).optional()
                    .orElseThrow(() -> Validate.invalid("refund_of does not exist"));
            if (!"EXPENSE".equals(original.kind()) || !"POSTED".equals(original.status())) {
                throw Validate.invalid("refund_of must be a posted expense");
            }
            if (!original.currency().equals(account.currency())) {
                throw Validate.invalid("a refund must be received in the currency of the original expense (" + original.currency() + ")");
            }
            requireRefundCapacity(ctx.tenantId(), original, amount, null);
            categoryId = original.categoryId();
        } else if (req.categoryId() != null && !req.categoryId().isBlank()) {
            categoryId = reference.requireUsable(ctx.tenantId(), Validate.uuid("category_id", req.categoryId(), true), kind.name(), "category_id").id();
        }
        UUID id = UUID.randomUUID();
        OffsetDateTime now = now(ctx);
        jdbc.sql("""
                insert into transactions (id, tenant_id, kind, status, account_id, amount, currency, category_id, refund_of, occurred_on,
                                          payee, note, created_by, created_at, updated_at)
                values (:id, :t, :k, 'POSTED', :a, :amt, :c, :cat, :ro, :d, :p, :n, :u, :now, :now)
                """)
                .param("id", id).param("t", ctx.tenantId()).param("k", kind.name()).param("a", account.id()).param("amt", amount)
                .param("c", account.currency()).param("cat", categoryId).param("ro", refundOf).param("d", date).param("p", payee)
                .param("n", note).param("u", ctx.userId()).param("now", now).update();
        insertTags(ctx, id, tags);
        audit.record(ctx, "TRANSACTION_CREATED", "TRANSACTION", id,
                kind + " " + Currencies.format(amount, account.currency()) + " " + account.currency() + " on " + date);
        return views(ctx.tenantId(), List.of(row(ctx.tenantId(), id, false))).get(0);
    }

    /** The refunds against one expense can never add up to more than the expense (the original row is locked by the caller). */
    private void requireRefundCapacity(UUID tenant, Row original, BigDecimal newRefund, UUID excludingRefund) {
        BigDecimal refunded = jdbc.sql("""
                select coalesce(sum(amount), 0) from transactions
                where tenant_id = :t and refund_of = :o and status <> 'VOIDED' and (cast(:x as uuid) is null or id <> :x)
                """).param("t", tenant).param("o", original.id()).param("x", excludingRefund).query(BigDecimal.class).single();
        if (refunded.add(newRefund).compareTo(original.amount()) > 0) {
            throw Validate.invalid("refunds cannot exceed the original expense (" + Currencies.format(original.amount().subtract(refunded), original.currency()) + " left to refund)");
        }
    }

    /**
     * Moves money between two of the user's accounts. Same currency: the destination receives the same amount, or less when
     * the difference is a fee. Different currencies: both amounts are stated by the user; no exchange rate is invented.
     */
    @Transactional
    public View transfer(FinanceContext ctx, TransferRequest req) {
        ctx.require(Action.CREATE);
        UUID fromId = Validate.uuid("from_account_id", req.fromAccountId(), true);
        UUID toId = Validate.uuid("to_account_id", req.toAccountId(), true);
        if (fromId.equals(toId)) {
            throw Validate.invalid("choose two different accounts");
        }
        AccountService.Row from = accounts.requireUsable(ctx.tenantId(), fromId, "from_account_id");
        AccountService.Row to = accounts.requireUsable(ctx.tenantId(), toId, "to_account_id");
        BigDecimal amount = Amounts.parse("amount", req.amount(), from.currency(), Amounts.Sign.POSITIVE);
        BigDecimal toAmount;
        if (from.currency().equals(to.currency())) {
            toAmount = req.toAmount() == null ? amount : Amounts.parse("to_amount", req.toAmount(), to.currency(), Amounts.Sign.POSITIVE);
            if (toAmount.compareTo(amount) > 0) {
                throw Validate.invalid("to_amount cannot exceed amount in the same currency (the difference is a transfer fee)");
            }
        } else {
            if (req.toAmount() == null) {
                throw Validate.invalid("to_amount is required when the accounts use different currencies");
            }
            toAmount = Amounts.parse("to_amount", req.toAmount(), to.currency(), Amounts.Sign.POSITIVE);
        }
        LocalDate date = Validate.date("occurred_on", req.occurredOn(), true);
        checkDate(ctx, date, from.openingDate(), to.openingDate());
        String note = Validate.text("note", req.note(), 1, 1000, false);
        UUID id = UUID.randomUUID();
        OffsetDateTime now = now(ctx);
        jdbc.sql("""
                insert into transactions (id, tenant_id, kind, status, account_id, to_account_id, amount, currency, to_amount, to_currency,
                                          occurred_on, note, created_by, created_at, updated_at)
                values (:id, :t, 'TRANSFER', 'POSTED', :f, :to, :amt, :c, :tamt, :tc, :d, :n, :u, :now, :now)
                """)
                .param("id", id).param("t", ctx.tenantId()).param("f", fromId).param("to", toId).param("amt", amount)
                .param("c", from.currency()).param("tamt", toAmount).param("tc", to.currency()).param("d", date).param("n", note)
                .param("u", ctx.userId()).param("now", now).update();
        audit.record(ctx, "TRANSFER_CREATED", "TRANSACTION", id, Currencies.format(amount, from.currency()) + " " + from.currency()
                + " -> " + Currencies.format(toAmount, to.currency()) + " " + to.currency() + " on " + date);
        return views(ctx.tenantId(), List.of(row(ctx.tenantId(), id, false))).get(0);
    }

    // ---- editing ----

    private static String describe(Row r) {
        return Currencies.format(r.amount(), r.currency()) + " " + r.occurredOn() + " cat=" + r.categoryId();
    }

    @Transactional
    public View edit(FinanceContext ctx, UUID id, EditRequest req) {
        ctx.require(Action.UPDATE);
        int version = Validate.version(req.version());
        Row row = row(ctx.tenantId(), id, true);
        if (row.version() != version) {
            throw new ApiException(ErrorCode.CONFLICT, "This transaction was changed elsewhere; reload and try again");
        }
        if ("VOIDED".equals(row.status())) {
            throw new ApiException(ErrorCode.CONFLICT, "A voided transaction cannot be edited; restore it first");
        }
        boolean transfer = "TRANSFER".equals(row.kind());
        boolean adjustment = "ADJUSTMENT".equals(row.kind());
        if (adjustment && (req.amount() != null || req.occurredOn() != null)) {
            throw Validate.invalid("an adjustment's amount and date cannot be edited; void it and make a new one");
        }
        BigDecimal amount = row.amount();
        BigDecimal toAmount = row.toAmount();
        if (req.amount() != null) {
            amount = Amounts.parse("amount", req.amount(), row.currency(), Amounts.Sign.POSITIVE);
            if (transfer && req.toAmount() == null && row.currency().equals(row.toCurrency())) {
                // A fee-free transfer stays fee-free; a transfer with a fee needs the new destination amount stated.
                if (row.toAmount().compareTo(row.amount()) == 0) {
                    toAmount = amount;
                } else {
                    throw Validate.invalid("to_amount is required when changing the amount of a transfer that has a fee");
                }
            }
        }
        if (req.toAmount() != null) {
            if (!transfer) {
                throw Validate.invalid("to_amount only applies to transfers");
            }
            toAmount = Amounts.parse("to_amount", req.toAmount(), row.toCurrency(), Amounts.Sign.POSITIVE);
        }
        if (transfer && row.currency().equals(row.toCurrency()) && toAmount.compareTo(amount) > 0) {
            throw Validate.invalid("to_amount cannot exceed amount in the same currency");
        }
        if (transfer && !row.currency().equals(row.toCurrency()) && req.amount() != null && req.toAmount() == null) {
            throw Validate.invalid("to_amount is required when changing a cross-currency transfer's amount");
        }
        LocalDate date = row.occurredOn();
        if (req.occurredOn() != null) {
            date = Validate.date("occurred_on", req.occurredOn(), true);
            LocalDate opening = accounts.require(ctx.tenantId(), row.accountId()).openingDate();
            LocalDate openingTo = transfer ? accounts.require(ctx.tenantId(), row.toAccountId()).openingDate() : opening;
            checkDate(ctx, date, opening, openingTo);
        }
        UUID categoryId = row.categoryId();
        if (Boolean.TRUE.equals(req.uncategorized()) || (req.categoryId() != null && !req.categoryId().isBlank())) {
            if (transfer || adjustment || "REFUND".equals(row.kind())) {
                throw Validate.invalid("this kind of transaction has no category");
            }
            categoryId = Boolean.TRUE.equals(req.uncategorized()) ? null
                    : reference.requireUsable(ctx.tenantId(), Validate.uuid("category_id", req.categoryId(), true), row.kind(), "category_id").id();
        }
        String payee = req.payee() == null ? row.payee() : Validate.text("payee", req.payee(), 1, 120, false);
        String note = req.note() == null ? row.note() : Validate.text("note", req.note(), 1, 1000, false);
        List<String> tags = req.tags() == null ? null : Validate.tags(req.tags());

        if ("EXPENSE".equals(row.kind())) {
            BigDecimal refunded = jdbc.sql("select coalesce(sum(amount), 0) from transactions where tenant_id = :t and refund_of = :o and status <> 'VOIDED'")
                    .param("t", ctx.tenantId()).param("o", id).query(BigDecimal.class).single();
            if (amount.compareTo(refunded) < 0) {
                throw Validate.invalid("amount cannot be lower than the refunds already recorded (" + Currencies.format(refunded, row.currency()) + ")");
            }
        } else if ("REFUND".equals(row.kind())) {
            Row original = row(ctx.tenantId(), row.refundOf(), true);
            requireRefundCapacity(ctx.tenantId(), original, amount, id);
        }
        int updated = jdbc.sql("""
                update transactions set amount = :amt, to_amount = :tamt, occurred_on = :d, category_id = :cat, payee = :p, note = :n,
                       version = version + 1, updated_at = :now
                where tenant_id = :t and id = :id and version = :v
                """)
                .param("amt", amount).param("tamt", toAmount).param("d", date).param("cat", categoryId).param("p", payee)
                .param("n", note).param("now", now(ctx)).param("t", ctx.tenantId()).param("id", id).param("v", version).update();
        if (updated == 0) {
            throw new ApiException(ErrorCode.CONFLICT, "This transaction was changed elsewhere; reload and try again");
        }
        if (tags != null) {
            jdbc.sql("delete from transaction_tags where tenant_id = :t and transaction_id = :x").param("t", ctx.tenantId()).param("x", id).update();
            insertTags(ctx, id, tags);
        }
        Row after = row(ctx.tenantId(), id, false);
        audit.record(ctx, "TRANSACTION_EDITED", "TRANSACTION", id, "before [" + describe(row) + "] after [" + describe(after) + "]"
                + (tags != null ? " tags=" + tags : ""));
        return views(ctx.tenantId(), List.of(after)).get(0);
    }

    // ---- lifecycle ----

    @Transactional
    public View voidTransaction(FinanceContext ctx, UUID id, String reasonRaw) {
        ctx.require(Action.ARCHIVE);
        String reason = Validate.text("reason", reasonRaw, 1, 200, true);
        Row row = row(ctx.tenantId(), id, true);
        if ("VOIDED".equals(row.status())) {
            throw new ApiException(ErrorCode.CONFLICT, "Already voided");
        }
        if ("EXPENSE".equals(row.kind()) && jdbc.sql("select count(*) from transactions where tenant_id = :t and refund_of = :o and status <> 'VOIDED'")
                .param("t", ctx.tenantId()).param("o", id).query(Long.class).single() > 0) {
            throw new ApiException(ErrorCode.CONFLICT, "Void its refunds first");
        }
        jdbc.sql("update transactions set status = 'VOIDED', voided_at = :now, void_reason = :r, version = version + 1, updated_at = :now where tenant_id = :t and id = :id")
                .param("now", now(ctx)).param("r", reason).param("t", ctx.tenantId()).param("id", id).update();
        audit.record(ctx, "TRANSACTION_VOIDED", "TRANSACTION", id, reason);
        return views(ctx.tenantId(), List.of(row(ctx.tenantId(), id, false))).get(0);
    }

    @Transactional
    public View restore(FinanceContext ctx, UUID id) {
        ctx.require(Action.ARCHIVE);
        Row row = row(ctx.tenantId(), id, true);
        if (!"VOIDED".equals(row.status())) {
            throw new ApiException(ErrorCode.CONFLICT, "Only a voided transaction can be restored");
        }
        if ("REFUND".equals(row.kind())) {
            Row original = row(ctx.tenantId(), row.refundOf(), true);
            if (!"POSTED".equals(original.status())) {
                throw new ApiException(ErrorCode.CONFLICT, "Restore the original expense first");
            }
            requireRefundCapacity(ctx.tenantId(), original, row.amount(), id);
        }
        jdbc.sql("update transactions set status = 'POSTED', voided_at = null, void_reason = null, version = version + 1, updated_at = :now where tenant_id = :t and id = :id")
                .param("now", now(ctx)).param("t", ctx.tenantId()).param("id", id).update();
        audit.record(ctx, "TRANSACTION_RESTORED", "TRANSACTION", id, null);
        return views(ctx.tenantId(), List.of(row(ctx.tenantId(), id, false))).get(0);
    }

    /** Turns a draft (for example one generated by a recurring rule) into a real, counted transaction. */
    @Transactional
    public View confirm(FinanceContext ctx, UUID id) {
        ctx.require(Action.UPDATE);
        Row row = row(ctx.tenantId(), id, true);
        if (!"DRAFT".equals(row.status())) {
            throw new ApiException(ErrorCode.CONFLICT, "Only a draft can be confirmed");
        }
        jdbc.sql("update transactions set status = 'POSTED', version = version + 1, updated_at = :now where tenant_id = :t and id = :id")
                .param("now", now(ctx)).param("t", ctx.tenantId()).param("id", id).update();
        audit.record(ctx, "TRANSACTION_CONFIRMED", "TRANSACTION", id, null);
        return views(ctx.tenantId(), List.of(row(ctx.tenantId(), id, false))).get(0);
    }

    static String normalizeKind(String kind) {
        return kind == null ? null : kind.trim().toUpperCase(Locale.ROOT);
    }
}
